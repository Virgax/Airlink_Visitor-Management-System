import Link from "next/link";
import { notFound } from "next/navigation";
import { getTranslations } from "next-intl/server";
import { ArrowLeft, ArrowRight } from "lucide-react";
import { AppShell } from "@/components/AppShell";
import { Icon } from "@/components/Icon";
import { getSessionUser } from "@/lib/auth/session";
import { findGuide, HELP_GUIDES } from "@/lib/help/guides";
import { HELP_ICONS } from "@/lib/help/icons";

export function generateStaticParams() {
  return HELP_GUIDES.map((g) => ({ slug: g.slug }));
}

/** Help bodies are plain text: blank-line separated paragraphs, lines starting with "- " become list items. */
function Body({ text }: { text: string }) {
  const blocks = text.split("\n").map((l) => l.trim()).filter(Boolean);
  const out: React.ReactNode[] = [];
  let list: string[] = [];
  const flush = () => {
    if (list.length) {
      out.push(<ul key={`l${out.length}`} className="list-disc space-y-1 pl-5">{list.map((li, i) => <li key={i}>{li}</li>)}</ul>);
      list = [];
    }
  };
  for (const line of blocks) {
    if (line.startsWith("- ")) list.push(line.slice(2));
    else {
      flush();
      out.push(<p key={`p${out.length}`}>{line}</p>);
    }
  }
  flush();
  return <div className="space-y-2 text-text">{out}</div>;
}

export default async function HelpGuidePage({ params }: { params: Promise<{ slug: string }> }) {
  const { slug } = await params;
  const guide = findGuide(slug);
  if (!guide) notFound();
  const user = await getSessionUser();
  const t = await getTranslations("help");
  const index = HELP_GUIDES.findIndex((g) => g.slug === guide.slug);
  const prev = HELP_GUIDES[index - 1];
  const next = HELP_GUIDES[index + 1];

  return (
    <AppShell user={user && !user.guardDeviceId ? user : null} kiosk={!!user?.guardDeviceId}>
      <article className="mx-auto max-w-3xl">
        <Link href="/help" className="muted inline-flex items-center gap-1 text-sm hover:underline"><Icon icon={ArrowLeft} size={16} /> {t("back")}</Link>
        <div className="mt-3 flex items-start gap-3">
          <span className="rounded-lg bg-surface-2 p-2"><Icon icon={HELP_ICONS[guide.icon]} size={24} /></span>
          <div>
            <h1 className="text-2xl font-semibold">{t(`guides.${guide.slug}.title`)}</h1>
            <p className="muted mt-1">{t(`guides.${guide.slug}.summary`)}</p>
            <p className="mt-1 text-xs text-text-muted">{t("forLabel")}: {guide.audience.map((a) => t(`audiences.${a}`)).join(" · ")}</p>
          </div>
        </div>

        <ol className="mt-8 space-y-10" data-testid="help-steps">
          {guide.steps.map((s, i) => {
            const title = t(`guides.${guide.slug}.steps.${s.key}.title`);
            return (
              <li key={s.key} id={s.key} className="scroll-mt-20">
                <div className="flex items-baseline gap-3">
                  <span className="flex h-8 w-8 shrink-0 items-center justify-center rounded-full bg-primary text-sm font-semibold text-primary-contrast" aria-label={t("step", { n: i + 1 })}>{i + 1}</span>
                  <h2 className="text-lg font-semibold">{title}</h2>
                </div>
                <div className="mt-3 pl-11">
                  <Body text={t(`guides.${guide.slug}.steps.${s.key}.body`)} />
                  {s.shot ? (
                    <figure className="mt-4">
                      {/* Static screenshots regenerated by `npm run help:screenshots`; plain <img> keeps them out of the optimizer. */}
                      {/* eslint-disable-next-line @next/next/no-img-element */}
                      <img src={`/help/${s.shot}.png`} alt={t("screenshotAlt", { title })} loading="lazy" className={`w-full rounded-lg border border-border bg-surface shadow-sm ${s.kiosk ? "max-w-xl" : ""}`} data-testid="help-shot" />
                    </figure>
                  ) : null}
                </div>
              </li>
            );
          })}
        </ol>

        {guide.related?.length ? (
          <section className="mt-12 border-t border-border pt-6">
            <h2 className="mb-2 font-semibold">{t("related")}</h2>
            <ul className="flex flex-wrap gap-2">
              {guide.related.map((r) => (
                <li key={r}><Link href={`/help/${r}`} className="btn-secondary text-sm">{t(`guides.${r}.title`)}</Link></li>
              ))}
            </ul>
          </section>
        ) : null}

        <nav className="mt-8 flex flex-wrap justify-between gap-2 text-sm" aria-label={t("title")}>
          {prev ? <Link href={`/help/${prev.slug}`} className="inline-flex items-center gap-1 hover:underline"><Icon icon={ArrowLeft} size={16} /> {t("prev")}: {t(`guides.${prev.slug}.title`)}</Link> : <span />}
          {next ? <Link href={`/help/${next.slug}`} className="inline-flex items-center gap-1 hover:underline">{t("next")}: {t(`guides.${next.slug}.title`)} <Icon icon={ArrowRight} size={16} /></Link> : null}
        </nav>
      </article>
    </AppShell>
  );
}
